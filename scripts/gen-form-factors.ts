/**
 * Regenerate src/lib/simulation/kernel/form-factor-coefficients.ts from the
 * `elements_info.yaml` table shipped inside the `debyecalculator` Python
 * package (installed into backend/.venv).
 *
 * Only a[5], c, b[5] are emitted — the kernel (debye.ts) never reads
 * neutronLength, atomicNumber or atomicRadius, so those source columns are
 * dropped.
 *
 * The source file's rows are a fixed, regular format (`Key : [ .. 14 floats
 * or null .. ]`), so this parses it with a plain line regex instead of
 * pulling in a YAML library for one table.
 *
 * Usage: pnpm tsx scripts/gen-form-factors.ts [path/to/elements_info.yaml]
 */
import { execFileSync } from 'node:child_process';
import { existsSync, globSync, readFileSync, writeFileSync } from 'node:fs';
import process from 'node:process';

const DEFAULT_GLOB =
  'backend/.venv/lib/python*/site-packages/debyecalculator/utility/elements_info.yaml';
const OUT_PATH = 'src/lib/simulation/kernel/form-factor-coefficients.ts';

function findSourcePath(): string {
  const argPath = process.argv[2];
  if (argPath) {
    if (!existsSync(argPath)) {
      throw new Error(`elements_info.yaml not found at "${argPath}"`);
    }
    return argPath;
  }
  const [found] = globSync(DEFAULT_GLOB);
  if (!found) {
    throw new Error(
      `Could not find elements_info.yaml via glob "${DEFAULT_GLOB}". ` +
        `Run "uv sync" in backend/, or pass the path explicitly: ` +
        `pnpm tsx scripts/gen-form-factors.ts <path>`,
    );
  }
  return found;
}

// Matches lines like: `H    :  [  0.413048,   ..., 1, .25]`
const ROW_RE = /^(\S+)\s*:\s*\[\s*(.+?)\s*\]\s*$/;

interface Row {
  key: string;
  a: [number, number, number, number, number];
  c: number;
  b: [number, number, number, number, number];
}

function parseYaml(text: string): Row[] {
  const rows: Row[] = [];
  for (const line of text.split('\n')) {
    const match = ROW_RE.exec(line.trim());
    if (!match) continue;
    const [, key, fields] = match;
    const values = fields.split(',').map((v) => Number(v.trim()));
    // Source column order: a1..a5, c, b1..b5, Coh_b(n), atomicNumber, atomicRadius.
    if (values.length < 11 || values.slice(0, 11).some(Number.isNaN)) {
      throw new Error(`Unexpected row shape for "${key}": ${line}`);
    }
    rows.push({
      key,
      a: values.slice(0, 5) as Row['a'],
      c: values[5],
      b: values.slice(6, 11) as Row['b'],
    });
  }
  if (rows.length === 0) {
    throw new Error('No element rows parsed from source YAML.');
  }
  return rows;
}

function render(rows: Row[], sourcePath: string): string {
  const entries = rows
    .map(
      (r) =>
        `    ${JSON.stringify(r.key)}: {\n` +
        `      a: [${r.a.join(', ')}],\n` +
        `      c: ${r.c},\n` +
        `      b: [${r.b.join(', ')}],\n` +
        `    },`,
    )
    .join('\n');

  return `// X-ray form-factor coefficients per element (Waasmaier & Kirfel 1995).
// GENERATED by scripts/gen-form-factors.ts from ${sourcePath}
// (elements_info.yaml, shipped inside the \`debyecalculator\` Python package).
// Re-run: pnpm tsx scripts/gen-form-factors.ts
//
// Layout matches the source table's leading columns: a[5] Gaussian
// amplitudes, c constant, b[5] Gaussian exponents. The source also carries
// neutronLength, atomicNumber and atomicRadius columns, which are dropped
// here — debye.ts only reads a, b, c.

export interface FormFactorCoefficients {
  /** Five Gaussian amplitude coefficients a1..a5. */
  a: [number, number, number, number, number];
  /** Constant offset c. */
  c: number;
  /** Five Gaussian exponent coefficients b1..b5. */
  b: [number, number, number, number, number];
}

export const FORM_FACTOR_COEFFICIENTS: Record<string, FormFactorCoefficients> =
  {
${entries}
  };
`;
}

const sourcePath = findSourcePath();
const rows = parseYaml(readFileSync(sourcePath, 'utf8'));
writeFileSync(OUT_PATH, render(rows, sourcePath));
execFileSync('pnpm', ['exec', 'prettier', '--write', OUT_PATH], {
  stdio: 'inherit',
});
console.log(
  `Wrote ${rows.length} elements to ${OUT_PATH} (source: ${sourcePath})`,
);
